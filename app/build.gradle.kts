// Google Services solo se aplica si el archivo google-services.json existe.
// Esto permite que el proyecto compile y corra (en modo local/invitado) ANTES
// de configurar Firebase. Cuando agregues tu propio google-services.json en
// esta carpeta (app/), vuelve a sincronizar y Firebase quedará activo.
val googleServicesFile = file("google-services.json")
if (googleServicesFile.exists()) {
    apply(plugin = "com.google.gms.google-services")
}

